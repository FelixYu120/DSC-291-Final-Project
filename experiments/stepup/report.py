"""Turn results.csv, importance.csv and gcvi_months.csv of stepup.py into README.md (plain tables)."""
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
COHORT_ORDER = ["zimbabwe_lacuna_2022_2023", "malawi_2022", "malawi_2023", "kenya_oaf_2019_2020", "zimbabwe_2024"]


def num(v, digits=3):
    return "" if pd.isna(v) else f"{v:.{digits}f}"


def ci(v, lo, hi):
    return "" if pd.isna(v) else f"{v:+.3f} ({lo:+.3f} to {hi:+.3f})"


def main() -> int:
    res = pd.read_csv(HERE / "results.csv")
    imp = pd.read_csv(HERE / "importance.csv")
    gm = pd.read_csv(HERE / "gcvi_months.csv")
    lines = ["# Step-up ladder: where does the R² come from?", "",
             "Generated by `stepup.py` and `report.py`. Same fields and `s1_cc2km` folds as step 8: fold-0 fields train, "
             "folds 1-4 are scored. Paired cluster bootstrap against A1 (Ridge on the 10 season indices), 2,000 draws, "
             "seed 20261029; `p Holm` corrects the rank p-value for every row of the cohort. **R² between** = how well the "
             "cluster (village) means are predicted; **R² within** = how well the deviations from the village mean are "
             "predicted; **train R²** minus R² shows overfitting. The pairwise rank model predicts order only.", ""]
    for cohort in COHORT_ORDER:
        d = res[res.cohort == cohort]
        if d.empty:
            continue
        lines += [f"## {cohort} ({d.role.iloc[0]})", "", "### The ladder (Ridge head)", "",
                  "| Step | Features | R² | RMSE | R² between | R² within | Rank inside clusters | Train R² | Rank vs A1 | RMSE vs A1 | p Holm |",
                  "|---|---:|---:|---:|---:|---:|---:|---:|---|---|---:|"]
        ladder = d[d["head"].isin(["Ridge", "-", "kNN"])]
        for r in ladder.itertuples():
            lines.append(f"| {r.step} | {r.n_features} | {num(r.r2)} | {num(r.rmse)} | {num(r.r2_between)} | {num(r.r2_within)} | "
                         f"{num(r.rank_inside_clusters)} | {num(r.train_r2)} | {ci(r.rank_vs_A1, r.rank_lo, r.rank_hi)} | "
                         f"{ci(r.rmse_vs_A1, r.rmse_lo, r.rmse_hi)} | {num(r.p_rank_holm)} |")
        lines += ["", "### Bayesian heads on the same features", "",
                  "| Step | Head | R² | R² within | Rank inside clusters | Train R² | Rank vs A1 | p Holm |", "|---|---|---:|---:|---:|---:|---|---:|"]
        for r in d[~d["head"].isin(["Ridge", "-", "kNN"])].itertuples():
            lines.append(f"| {r.step} | {r.head} | {num(r.r2)} | {num(r.r2_within)} | {num(r.rank_inside_clusters)} | "
                         f"{num(r.train_r2)} | {ci(r.rank_vs_A1, r.rank_lo, r.rank_hi)} | {num(r.p_rank_holm)} |")
        i = imp[imp.cohort == cohort]
        lines += ["", "### Which bands and months carry the monthly-band model (shuffle one block, Ridge S7)", "",
                  "| Block | R² drop | Rank drop |", "|---|---:|---:|"]
        for r in i.sort_values("r2_drop", ascending=False).itertuples():
            lines.append(f"| {r.block} | {r.r2_drop:+.3f} | {r.rank_drop:+.3f} |")
        g = gm[gm.cohort == cohort]
        lines += ["", "### GCVI month by month (folds 1-4, Spearman with yield)", "",
                  "| Month of season | Calendar month | Fields | All fields | Between clusters | Inside clusters |", "|---:|---|---:|---:|---:|---:|"]
        for r in g.itertuples():
            lines.append(f"| {r.k} | {r.months} | {r.fields} | {num(r.all)} | {num(r.between_clusters)} | {num(r.inside_clusters)} |")
        lines.append("")
    (HERE / "README.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"README.md written: {len(lines)} lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
